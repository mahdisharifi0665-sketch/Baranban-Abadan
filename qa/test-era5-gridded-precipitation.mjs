import assert from "node:assert/strict";
import {buildEra5ArchiveUrl,parseEra5PrecipitationResponse,fetchEra5Precipitation} from "../src/era5-gridded-precipitation.mjs";
const url=new URL(buildEra5ArchiveUrl({startDate:"2026-11-01",endDate:"2026-11-02"}));
assert.equal(url.searchParams.get("models"),"era5");
assert.equal(url.searchParams.get("hourly"),"precipitation");
assert.equal(url.searchParams.get("timezone"),"UTC");
assert.equal(url.searchParams.get("cell_selection"),"nearest");
assert.throws(()=>buildEra5ArchiveUrl({startDate:"2026-02-30",endDate:"2026-03-01"}),/invalid_date_range/);
assert.throws(()=>buildEra5ArchiveUrl({startDate:"2026-11-02",endDate:"2026-11-01"}),/invalid_date_range/);
const payload={latitude:28,longitude:51.75,hourly:{time:["2026-11-01T01:00Z","2026-11-01T02:00Z","2026-11-01T03:00Z"],precipitation:[0,1.25,null]}};
const archive=parseEra5PrecipitationResponse(payload,{retrievedAtUtc:"2026-11-03T00:00:00Z"});
assert.equal(archive.record_count,3);
assert.equal(archive.records[0].interval_start_utc,"2026-11-01T00:00:00.000Z");
assert.equal(archive.records[0].interval_end_utc,"2026-11-01T01:00:00.000Z");
assert.equal(archive.records[0].value_mm,0);
assert.equal(archive.records[1].value_mm,1.25);
assert.equal(archive.records[2].value_mm,null);
assert.equal(archive.records[2].quality_status,"missing");
assert.ok(archive.records.every(x=>x.source.source_type==="reanalysis_grid_estimate"));
assert.ok(archive.records.every(x=>x.quality_flags.includes("reanalysis_not_ground_station")||x.quality_flags.includes("source_value_missing")));
assert.throws(()=>parseEra5PrecipitationResponse({...payload,hourly:{...payload.hourly,precipitation:[0]} }),/array_length_mismatch/);
assert.throws(()=>parseEra5PrecipitationResponse({...payload,hourly:{time:["2026-11-01T01:00+03:30"],precipitation:[0]}}),/must_be_utc/);
let requested="";
const fetched=await fetchEra5Precipitation({startDate:"2026-11-01",endDate:"2026-11-01",fetchImpl:async u=>{requested=u;return {ok:true,json:async()=>({latitude:28,longitude:51.75,hourly:{time:["2026-11-01T01:00Z"],precipitation:[0]}})}},retrievedAtUtc:"2026-11-02T00:00:00Z"});
assert.equal(fetched.record_count,1);
assert.match(requested,/models=era5/);
console.log("ERA5 gridded precipitation adapter tests passed");
